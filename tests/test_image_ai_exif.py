from io import BytesIO
from pathlib import Path
from PIL import Image
from nextlife.storage.db import get_db_session
from nextlife.storage.models import ItemPhoto
from nextlife.media.ai_edit import _get_clean_original_exif

def test_exif_preservation_and_ai_sanitization(tmp_path):
    orig_img = Image.new("RGB", (100, 100), (255, 0, 0))
    exif = orig_img.getexif()
    exif[271] = "samsung"
    exif[272] = "SM-G986B"
    exif[305] = "G986BXXSNHYB1"
    exif[306] = "2026:10:21 16:19:11"
    exif[270] = "Generated by Stable Diffusion AI model"  # Forbidden AI tag
    exif_bytes = exif.tobytes()

    orig_path = tmp_path / "orig.jpg"
    orig_img.save(orig_path, format="JPEG", exif=exif_bytes)

    with get_db_session() as session:
        p_orig = ItemPhoto(
            id="orig-photo-exif-test",
            item_code="130",
            role="ORIGINAL",
            path=str(orig_path),
            sha256="fake-sha",
            width=100,
            height=100,
            derived_from_id=None,
        )
        clean_bytes = _get_clean_original_exif(session, p_orig, 200, 200)
        assert clean_bytes is not None

    saved_img = Image.new("RGB", (200, 200), (0, 255, 0))
    out_path = tmp_path / "derived.jpg"
    saved_img.save(out_path, format="JPEG", exif=clean_bytes)

    with Image.open(out_path) as chk:
        chk_ex = chk.getexif()
        assert chk_ex[271] == "samsung"
        assert chk_ex[272] == "SM-G986B"
        assert chk_ex[305] == "G986BXXSNHYB1"
        assert chk_ex[306] == "2026:10:21 16:19:11"
        assert chk_ex[256] == 200
        assert chk_ex[257] == 200
        assert 270 not in chk_ex or "AI" not in chk_ex[270]
